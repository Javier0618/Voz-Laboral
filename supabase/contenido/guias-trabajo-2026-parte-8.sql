  $g$## Qué dice la ley
Los **factores de riesgo psicosocial** son las condiciones del trabajo que pueden afectar tu salud física y mental: la carga de trabajo, el estilo de mando, los turnos, las horas extra, el clima con los compañeros o la falta de pausas. La **Resolución 2646 de 2008** obliga a identificarlos, evaluarlos, prevenirlos, intervenirlos y monitorearlos de forma permanente (art. 1). Se aplica a empleadores públicos y privados, y también a quienes contratan por prestación de servicios (art. 2).

**Lo que debe hacer tu empresa:**
- **Evaluar los factores de riesgo psicosocial** del trabajo, como mínimo: la gestión de la organización (estilo de mando, formas de pago y contratación, evaluación del desempeño), la organización del trabajo, las relaciones con el grupo, las demandas de la tarea (carga mental y emocional), la jornada (pausas, trabajo nocturno, turnos, horas extra y descansos) y las condiciones del lugar de trabajo (art. 6 de la Resolución 2646 de 2008).
- **Usar instrumentos validados en el país** para esa evaluación (art. 10).
- **Guardar reserva** de la información. La evaluación de tus condiciones de salud debe ir precedida de tu **consentimiento informado** (art. 11).
- **Tener un programa de vigilancia** cuando los trabajadores estén expuestos a factores de riesgo psicosocial altos, con apoyo de expertos y de la ARL (art. 16).
- **Incluir en su sistema de seguridad y salud en el trabajo el monitoreo permanente** del riesgo psicosocial (art. 9 de la Ley 1616 de 2013). Desde 2025, la ley también le pide implementar medidas para el bienestar y la salud mental durante la jornada y garantizar un ambiente libre de acoso laboral (parágrafo añadido por la Ley 2460 de 2025).

**Las ARL** deben tener programas de promoción de la salud mental y prevención del trastorno mental para las empresas afiliadas, y asegurar que estas monitoreen el riesgo psicosocial (art. 9 de la Ley 1616 de 2013).

**Protección contra el despido:** la reforma laboral prohíbe expresamente al empleador despedir o presionar la renuncia de una persona por razones de enfermedad o afectaciones a la salud mental (art. 59, numeral 15, del CST, añadido por la Ley 2466 de 2025).

## En la práctica
- La evaluación suele hacerse con cuestionarios que responde el personal. Tus respuestas son confidenciales y solo sirven para fines de salud ocupacional.
- Si el estrés del trabajo te causa una enfermedad, puede **calificarse como enfermedad laboral**. Para decidir si su origen es laboral se usa un protocolo oficial para las patologías derivadas del estrés (arts. 18 y 19 de la Resolución 2646 de 2008). El empleador debe aportar la información sobre tu exposición a factores psicosociales (art. 20).
- Si el origen es laboral, la ARL cubre la atención y las prestaciones. Si es común, las cubre la EPS.
- El acoso laboral es uno de los riesgos psicosociales más graves. La Ley 1010 de 2006 lo define y fija medidas para prevenirlo y corregirlo.

## Errores comunes
- **«El estrés es un problema personal, la empresa no tiene nada que ver.»** La ley obliga a la empresa a evaluar y prevenir los factores de riesgo psicosocial del trabajo.
- **«Si digo que estoy mal, me pueden despedir.»** Despedir o presionar la renuncia por afectaciones a la salud mental está prohibido.
- **«La encuesta psicosocial la lee mi jefe.»** La información está sometida a reserva y solo se usa para salud ocupacional.
- **«Una enfermedad mental nunca es laboral.»** Puede serlo si se demuestra la relación con los factores de riesgo del trabajo.

## Qué puedes hacer
1. Si te sientes mal, consulta a tu EPS y cuéntale al médico cómo es tu trabajo: horarios, carga y trato. Si se trata de una emergencia, llama al **123**.
2. Pide por escrito a tu empresa información sobre su evaluación de riesgo psicosocial y sobre su programa de vigilancia.
3. Si crees que tu enfermedad es de origen laboral, pide a tu EPS o a tu ARL que califiquen su origen, y guarda las pruebas de tus condiciones de trabajo.
4. Si hay acoso, usa el procedimiento interno, confidencial y conciliatorio que tu empresa debe tener en su reglamento de trabajo (art. 9 de la Ley 1010 de 2006), o acude al Ministerio del Trabajo.
5. Si te presionan para renunciar o te despiden por tu salud mental, guarda las pruebas y busca asesoría de inmediato.

> Importante: esta guía es orientativa. No sustituye la atención en salud, la asesoría de un abogado ni una decisión del Ministerio del Trabajo.

