  $g$## Qué dice la ley
Desde el **2 de abril de 2026** rige un **nuevo Código Procesal del Trabajo y de la Seguridad Social** (Ley 2452 de 2025). Estos son los caminos para reclamar, de menor a mayor esfuerzo.

### 1. Reclamar por escrito a tu empleador
Es el primer paso y deja constancia. Un reclamo escrito sobre un derecho concreto **interrumpe la prescripción una sola vez**: desde ese día vuelve a contar el plazo de 3 años (arts. 488 y 489 del CST). Puedes hacerlo con un derecho de petición.

### 2. Conciliar
- La conciliación es **voluntaria**: no tienes que intentarla antes de demandar (art. 19 del Código Procesal del Trabajo).
- Puedes pedirla **antes del proceso** a los jueces laborales, sin perjuicio de otras autoridades que también pueden conciliar, como los inspectores del Ministerio del Trabajo (art. 20). Con la solicitud debes aportar los documentos que tengas o declarar bajo juramento que los hechos son ciertos.
- **Lo que no se puede conciliar:** los derechos ciertos e indiscutibles (art. 21). Por ejemplo, no puedes renunciar a prestaciones que ya se causaron y que la ley te reconoce sin discusión.
- También puede haber conciliación **dentro del proceso**: el juez invita a las partes a conciliar en la primera audiencia.

### 3. Demandar ante un juez laboral
- **Juez laboral municipal:** procesos de hasta **40 salarios mínimos**.
- **Juez laboral del circuito:** procesos de más de 40 salarios mínimos (art. 13). Donde no haya juez laboral, conoce el juez civil o promiscuo del circuito.
- **Dónde demandar:** tú eliges entre el **último lugar donde trabajaste** y el **domicilio de tu empleador** (art. 10).
- **Abogado:** por regla general debes actuar por medio de un abogado, salvo cuando la ley permita tu intervención directa (art. 39).
- **Si no puedes pagar el proceso:** pide el **amparo de pobreza** (arts. 109 a 112). Debes declarar bajo juramento que no puedes asumir los gastos sin afectar tu subsistencia o la de quienes dependen de ti, con una prueba sencilla como el **Sisbén A o B** o el **estrato 1**. Con el amparo no pagas gastos del proceso, no te condenan en costas, y el juez puede designarte un abogado.

### 4. Tutela (casos urgentes)
- Es para proteger **derechos fundamentales**, con un trámite rápido: **no pueden pasar más de 10 días** entre la solicitud y la decisión (art. 86 de la Constitución).
- **Solo procede si no tienes otro medio de defensa judicial**, salvo que la uses como mecanismo transitorio para evitar un **perjuicio irremediable** (art. 86).
- Puedes presentarla contra un empleador particular, porque entre trabajador y empleador hay subordinación.
- **No necesitas abogado** ni formalidades: basta explicar con claridad qué pasó, qué derecho se vulnera y quién lo hizo (art. 14 del Decreto 2591 de 1991).

## En la práctica
- **¿Qué camino elijo?**
  - Para cobrar salarios, prestaciones, liquidación o indemnizaciones, el camino habitual es la **conciliación o la demanda laboral**.
  - La **tutela** se usa cuando la situación es urgente y afecta tu sustento o un derecho fundamental: por ejemplo, el despido de una mujer embarazada o de alguien con estabilidad reforzada por salud, o cuando la falta de pago te deja sin lo mínimo para vivir.
- **El Ministerio del Trabajo** puede investigar, sancionar y conciliar, pero **no puede ordenar que te paguen** una suma concreta ni declarar derechos: eso le corresponde al juez.
- **Consultorios jurídicos:** muchas universidades tienen consultorios que atienden gratis. Son una buena primera parada.

## Errores comunes
- **«Primero tengo que conciliar para poder demandar.»** En asuntos laborales la conciliación no es obligatoria antes de la demanda.
- **«En la conciliación puedo aceptar menos de lo que la ley me reconoce.»** No se pueden conciliar los derechos ciertos e indiscutibles.
- **«La tutela sirve para cobrar cualquier deuda laboral.»** Es excepcional: procede cuando no hay otro medio eficaz o para evitar un perjuicio irremediable.
- **«Puedo esperar todo lo que quiera.»** Los derechos laborales prescriben en 3 años desde que son exigibles.
- **«Si no tengo plata, no puedo demandar.»** El amparo de pobreza existe justamente para eso.

## Qué puedes hacer
1. Reúne pruebas: contrato, desprendibles, correos, mensajes, horarios y nombres de testigos.
2. Envía un reclamo escrito o un derecho de petición a tu empleador, y guarda la constancia de entrega.
3. Si no responde o la respuesta no te satisface, busca orientación en un consultorio jurídico o con un abogado laboralista.
4. Intenta conciliar si crees que hay espacio para un acuerdo. Si no, presenta la demanda; pide el amparo de pobreza si no puedes pagar los gastos.
5. Si la situación es urgente y afecta tu sustento o tu salud, consulta si procede una tutela.

> Importante: esta guía es orientativa. Cada caso es distinto: antes de demandar, busca asesoría jurídica.

